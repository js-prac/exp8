function changeMouseOverColor() {
  document.getElementById("mouseBox").style.backgroundColor = "red";
}

function restoreMouseOverColor() {
  document.getElementById("mouseBox").style.backgroundColor = "blue";
}

function changeFocusColor() {
  document.getElementById("focusBox").style.backgroundColor = "#dbeafe";
}

function restoreFocusColor() {
  document.getElementById("focusBox").style.backgroundColor = "white";
}
